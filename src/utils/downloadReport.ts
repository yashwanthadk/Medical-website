import type { AnalysisDetail } from '../lib/api';

export function downloadAnalysisSummary(detail: AnalysisDetail): void {
  const lines: string[] = [
    '============================================================',
    'MediExplain AI — Educational Medical Report Summary',
    '============================================================',
    `Title: ${detail.title}`,
    `Report Type: ${detail.reportType.toUpperCase()}`,
    `Date Analyzed: ${new Date(detail.createdAt).toLocaleString()}`,
    `Status: ${detail.status}`,
    detail.clinicalNotes ? `Clinical Context Provided: ${detail.clinicalNotes}` : '',
    '',
    '--- PLAIN-LANGUAGE SUMMARY ---',
    detail.summaryPlain || 'No summary available.',
    '',
  ];

  if (detail.urgentFlag) {
    lines.push('!!! ATTENTION NOTICE !!!');
    lines.push(detail.urgentReason || 'Findings warrant prompt review by a qualified healthcare professional.');
    lines.push('');
  }

  if (detail.reportType === 'xray' && detail.structured) {
    const s = detail.structured;
    if (s.identifiableViewOrRegion) {
      lines.push(`Identifiable View/Region: ${s.identifiableViewOrRegion}`);
    }
    if (Array.isArray(s.visibleObservations) && s.visibleObservations.length > 0) {
      lines.push('', '--- VISIBLE OBSERVATIONS ---');
      for (const obs of s.visibleObservations) {
        lines.push(`• ${obs.region}: ${obs.observation}`);
        lines.push(`  Plain Explanation: ${obs.plainExplanation}`);
      }
    }
    if (Array.isArray(s.areasRequiringProfessionalReview) && s.areasRequiringProfessionalReview.length > 0) {
      lines.push('', '--- AREAS FOR CLINICAL REVIEW ---');
      s.areasRequiringProfessionalReview.forEach((a: string) => lines.push(`• ${a}`));
    }
    if (Array.isArray(s.cannotBeAssessedReliably) && s.cannotBeAssessedReliably.length > 0) {
      lines.push('', '--- CANNOT BE ASSESSED RELIABLY ---');
      s.cannotBeAssessedReliably.forEach((c: string) => lines.push(`• ${c}`));
    }
  }

  if (detail.reportType === 'mri' && detail.structured) {
    const s = detail.structured;
    if (s.anatomicalRegion) lines.push(`Anatomical Region: ${s.anatomicalRegion}`);
    if (s.sequenceAppearance) lines.push(`Sequence Appearance: ${s.sequenceAppearance}`);
    if (Array.isArray(s.visibleStructures) && s.visibleStructures.length > 0) {
      lines.push('', '--- VISIBLE STRUCTURES ---');
      for (const st of s.visibleStructures) {
        lines.push(`• ${st.structure}: ${st.observation}`);
        lines.push(`  Plain Explanation: ${st.plainExplanation}`);
      }
    }
    if (s.singleSliceLimitationNote) {
      lines.push('', '--- SINGLE-SLICE LIMITATION ---', s.singleSliceLimitationNote);
    }
  }

  if (detail.reportType === 'blood' && detail.bloodResults.length > 0) {
    lines.push('--- EXTRACTED BLOOD TEST RESULTS ---');
    for (const row of detail.bloodResults) {
      lines.push(
        `• ${row.test_name}: ${row.measured_value} ${row.unit} | Ref: ${row.reference_range} | Status: ${row.status} (Confidence: ${row.extraction_confidence})`
      );
      lines.push(`  Explanation: ${row.simple_explanation}`);
    }
    lines.push('');
  }

  if (detail.limitations) {
    lines.push('--- TECHNICAL LIMITATIONS ---', detail.limitations, '');
  }

  lines.push(
    '--- MEDICAL SAFETY DISCLAIMER ---',
    detail.disclaimer ||
      'This summary is generated by artificial intelligence strictly for educational understanding. It is NOT a medical diagnosis and does not replace evaluation by a licensed physician or radiologist.',
    '============================================================'
  );

  const blob = new Blob([lines.filter((l) => l !== undefined).join('\n')], {
    type: 'text/plain;charset=utf-8',
  });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  const slug = detail.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').slice(0, 40) || 'report';
  anchor.href = url;
  anchor.download = `mediexplain-${slug}-summary.txt`;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}
